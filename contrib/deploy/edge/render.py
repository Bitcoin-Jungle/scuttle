#!/usr/bin/env python3
"""Renders the nginx edge in front of scuttle's public services.

One template for every environment: an environment file (TOML) names the
hosts, their upstreams, who is trusted for the client address, who bypasses
rate limits and the limits themselves. The output is a single nginx file for
sites-enabled (it is included inside the http block).

The edge fronts the services we run, and only those:
- posd (the point of sale and Lightning address service): the OWASP Core Rule
  Set (ModSecurity) on every request, per-route rate limits, the operator API
  restricted to trusted networks, and JSON errors where clients parse them.
- captaind's public API (gRPC and gRPC-Web): an allowlist of the services it
  serves publicly, per-client and per-method rate limits answered as gRPC
  errors, and no WAF, whose rules cannot read protobuf.

    render.py regtest.toml name=scuttle-regtest domain=example.com > scuttle-edge
    render.py --hosts regtest.toml name=... domain=...   # the certificate's names

Host names in the environment file may use {name} and {domain}.
"""
import sys
import tomllib

# The gRPC services captaind serves on its public port (server/src/rpcserver/ark.rs).
ARK_SERVICES = ("bark_server.ArkService", "mailbox_server.MailboxService", "grpc.health.v1.Health")
# Methods that make captaind do real work per call (an invoice on the
# Lightning node, a cosignature, a scan): a tighter limit of their own.
ARK_COSTLY = ("StartLightningReceive", "RequestBoardCosign", "RecoverVtxosByXpub", "PrepareOffboard",
              "InitiateLightningPayment", "FetchBolt12Invoice", "RequestArkoorCosign",
              "RequestLightningPayHtlcCosign")

# Methods whose requests grow with the wallet (VTXO lists, transactions,
# signatures): the large body cap. Every other method gets the small one, so
# a method added to captaind later fails loudly (RESOURCE_EXHAUSTED, "request
# too large") until it is classified here.
ARK_LARGE = (
	"ArkService/RegisterVtxoTransactions", "ArkService/RegisterVtxos", "ArkService/RegisterBoardVtxo",
	"ArkService/RequestBoardCosign", "ArkService/RequestArkoorCosign", "ArkService/RequestLightningPayHtlcCosign",
	"ArkService/RequestLightningPayHtlcRevocation", "ArkService/InitiateLightningPayment",
	"ArkService/PrepareLightningReceiveClaim", "ArkService/ClaimLightningReceive",
	"ArkService/PrepareOffboard", "ArkService/FinishOffboard", "ArkService/SubmitPayment",
	"ArkService/ProvideVtxoSignatures", "ArkService/SubmitRoundParticipation", "ArkService/RequestLeafVtxoCosign",
	"ArkService/RequestForfeitNonces", "ArkService/ForfeitVtxos", "ArkService/GetVtxosByIds",
	"ArkService/GetVtxosStatusByIds", "MailboxService/PostArkoorMessage", "MailboxService/PostRecoveryVtxoIds",
)
# captaind keeps gRPC's default 4 MiB message limit; fixed-size requests
# (status checks, invoices, subscriptions) are well under 1 KB.
ARK_BODY_LARGE = "4m"
ARK_BODY_SMALL = "16k"
# HTTP/2 streams per client connection. A wallet holds two streams open
# (mailbox, rounds) and makes a few calls at a time. Behind a proxy that
# multiplexes many clients onto one connection (cloudflared), raise it.
DEFAULT_H2_STREAMS = 32

DEFAULT_LIMITS = {
	# zone: (rate, burst). Per client address, after the exemptions.
	"ark": ("30r/s", 120),
	"ark_costly": ("2r/s", 20),
	"pos": ("20r/s", 60),
	"pos_auth": ("30r/m", 10),
	"lnurl": ("60r/m", 20),
}
DEFAULT_CONN = 64

TLS_CIPHERS = ":".join([
	"ECDHE-ECDSA-AES128-GCM-SHA256", "ECDHE-RSA-AES128-GCM-SHA256",
	"ECDHE-ECDSA-AES256-GCM-SHA384", "ECDHE-RSA-AES256-GCM-SHA384",
	"ECDHE-ECDSA-CHACHA20-POLY1305", "ECDHE-RSA-CHACHA20-POLY1305",
])


def render(env):
	listen = env["listen"]
	limits = {**DEFAULT_LIMITS, **{k: (v["rate"], v["burst"]) for k, v in env.get("limits", {}).items()}}
	conn = env.get("conn_per_client", DEFAULT_CONN)
	out = []
	w = out.append

	w("# Generated by contrib/deploy/edge/render.py. Do not edit by hand.\n")
	w("log_format edge_json escape=json '{\"time\":\"$time_iso8601\",\"host\":\"$host\","
	  "\"client\":\"$remote_addr\",\"method\":\"$request_method\",\"uri\":\"$request_uri\","
	  "\"proto\":\"$server_protocol\",\"status\":$status,\"bytes\":$body_bytes_sent,\"request_bytes\":$request_length,"
	  "\"time_s\":$request_time,\"upstream\":\"$upstream_addr\",\"upstream_status\":\"$upstream_status\","
	  "\"upstream_s\":\"$upstream_response_time\",\"limit\":\"$limit_req_status\","
	  "\"grpc_status\":\"$sent_trailer_grpc_status$sent_http_grpc_status\",\"id\":\"$request_id\","
	  "\"ua\":\"$http_user_agent\"}';\n")

	# The client address. Behind a proxy that names the client, trust it only
	# from that proxy; facing the internet, the connection's own address.
	if env.get("real_ip_from"):
		for net in env["real_ip_from"]:
			w(f"set_real_ip_from {net};\n")
		w(f"real_ip_header {env['real_ip_header']};\n")

	w("\n# Rate limits key on the client; exempt clients (operators, load tests) get\n"
	  "# an empty key, which nginx does not count. The WAF still applies to them.\n")
	w("geo $edge_exempt {\n\tdefault 0;\n")
	for net in env.get("limit_exempt", []):
		w(f"\t{net} 1;\n")
	w("}\n")
	w("map $edge_exempt $edge_key {\n\t0 $binary_remote_addr;\n\t1 \"\";\n}\n")
	costly = "|".join(ARK_COSTLY)
	w("map $uri $ark_costly_key_on {\n\tdefault 0;\n"
	  f"\t\"~^/bark_server\\.ArkService/({costly})$\" 1;\n}}\n")
	w("map $ark_costly_key_on $ark_costly_key {\n\t0 \"\";\n\t1 $edge_key;\n}\n")
	for zone, (rate, _) in limits.items():
		key = "$ark_costly_key" if zone == "ark_costly" else "$edge_key"
		w(f"limit_req_zone {key} zone=edge_{zone}:10m rate={rate};\n")
	w("limit_conn_zone $edge_key zone=edge_conn:10m;\n")
	w("limit_req_status 429;\nlimit_conn_status 429;\nlimit_req_log_level warn;\n\n")

	services = "|".join(s.replace(".", "\\.") for s in ARK_SERVICES)
	w("# captaind's public gRPC services; anything else is answered at the edge.\n")
	w(f"map $uri $ark_allowed {{\n\tdefault 0;\n\t\"~^/({services})/[A-Za-z0-9]+$\" 1;\n}}\n")
	w("# Browsers speak gRPC-Web (and send CORS preflights), which captaind\n"
	  "# serves over plain HTTP; native wallets speak gRPC over HTTP/2.\n")
	w("map \"$request_method:$http_content_type\" $ark_grpc_web {\n\tdefault 0;\n"
	  "\t\"~^OPTIONS:\" 1;\n\t\"~^[A-Z]+:application/grpc-web\" 1;\n}\n")
	w("map $http_content_type $ark_error_type {\n\tdefault application/grpc;\n"
	  "\t\"~^application/grpc-web-text\" application/grpc-web-text+proto;\n"
	  "\t\"~^application/grpc-web\" application/grpc-web+proto;\n}\n\n")

	# Anything that is not one of our hosts: no certificate, no answer.
	w(f"server {{\n\tlisten {listen} ssl default_server;\n\thttp2 on;\n\tssl_reject_handshake on;\n}}\n\n")

	for site in env.get("ark", []):
		out.extend(ark_server(env, site, limits, conn))
	for site in env.get("posd", []):
		out.extend(posd_server(env, site, limits, conn))
	return "".join(out)


def common(env, host):
	hsts = "\tmore_set_headers \"Strict-Transport-Security: max-age=31536000\";\n" if env.get("hsts") else ""
	return (
		f"\tlisten {env['listen']} ssl;\n\thttp2 on;\n\tserver_name {host};\n"
		f"\tssl_certificate {env['tls_cert']};\n\tssl_certificate_key {env['tls_key']};\n"
		f"\tssl_ciphers {TLS_CIPHERS};\n\tssl_session_cache shared:edge_tls:10m;\n\tssl_session_tickets off;\n"
		"\taccess_log /var/log/nginx/edge-access.log edge_json;\n"
		"\tserver_tokens off;\n"
		"\tclient_header_timeout 10s;\n\tclient_body_timeout 20s;\n\tsend_timeout 30s;\n"
		"\tkeepalive_timeout 65s;\n\tlarge_client_header_buffers 4 16k;\n"
		"\tmore_clear_headers Server X-Powered-By;\n"
		"\tmore_set_headers \"X-Content-Type-Options: nosniff\";\n"
		f"{hsts}"
	)


def ark_server(env, site, limits, conn):
	host, upstream = site["host"], site["upstream"]
	ark, costly = limits["ark"], limits["ark_costly"]
	large, small = site.get("max_body_large", ARK_BODY_LARGE), site.get("max_body_small", ARK_BODY_SMALL)
	streams = env.get("http2_max_concurrent_streams", DEFAULT_H2_STREAMS)
	large_methods = "|".join(ARK_LARGE)
	grpc = f"""grpc_pass grpc://{upstream};
		grpc_set_header X-Request-ID $request_id;
		grpc_set_header X-Forwarded-For $remote_addr;
		# Mailbox and round streams stay open.
		grpc_read_timeout 1h;
		grpc_send_timeout 1h;"""
	web = f"""proxy_pass http://{upstream};
		proxy_http_version 1.1;
		proxy_set_header Host $host;
		proxy_set_header X-Request-ID $request_id;
		proxy_set_header X-Forwarded-For $remote_addr;
		proxy_buffering off;
		proxy_read_timeout 1h;"""
	error = lambda status, message: (
		f'more_set_headers "Content-Type: $ark_error_type" "grpc-status: {status}" "grpc-message: {message}"\n'
		'\t\t\t"Access-Control-Allow-Origin: *" "Access-Control-Expose-Headers: grpc-status,grpc-message";\n'
		'\t\treturn 204;')
	return [f"""# captaind's public API: {host}
server {{
{common(env, host)}	http2_max_concurrent_streams {streams};
	limit_conn edge_conn {conn};
	limit_req zone=edge_ark burst={ark[1]} nodelay;
	limit_req zone=edge_ark_costly burst={costly[1]} nodelay;
	modsecurity off;
	# Errors become gRPC statuses, also when raised in the named locations.
	recursive_error_pages on;
	error_page 404 = @unimplemented;
	error_page 413 = @too_large;
	error_page 429 = @limited;
	error_page 502 503 504 = @unavailable;
	# gRPC-Web (browsers, and their CORS preflights) is plain HTTP for
	# captaind: served by the named locations, one per body cap.
	error_page 418 = @grpc_web_small;
	error_page 419 = @grpc_web_large;

	# Body caps per method: small unless the method is listed as large.
	client_max_body_size {small};
	# A location of their own, so the cap applies when nginx first checks the
	# body (Content-Length, before any rewrite).
	location ~ "^/(bark_server|mailbox_server)\\.({large_methods})$" {{
		client_max_body_size {large};
		if ($ark_grpc_web) {{
			return 419;
		}}
		{grpc}
	}}
	location / {{
		if ($ark_allowed = 0) {{
			return 404;
		}}
		if ($ark_grpc_web) {{
			return 418;
		}}
		{grpc}
	}}
	location @grpc_web_small {{
		{web}
	}}
	location @grpc_web_large {{
		client_max_body_size {large};
		{web}
	}}
	# Errors as gRPC statuses (trailers-only), which gRPC and gRPC-Web clients
	# read; a plain HTTP status reaches the app as an opaque transport error.
	location @unimplemented {{
		{error(12, "unknown%20method")}
	}}
	location @too_large {{
		{error(8, "request%20too%20large")}
	}}
	location @limited {{
		{error(8, "rate%20limited")}
	}}
	location @unavailable {{
		{error(14, "unavailable")}
	}}
}}

"""]


def posd_server(env, site, limits, conn):
	host, upstream = site["host"], site["upstream"]
	allow = "".join(f"\t\tallow {net};\n" for net in env.get("admin_allow", []))
	proxy = (f"\t\tproxy_pass http://{upstream};\n"
	         "\t\tinclude /etc/nginx/scuttle-edge/proxy.conf;\n")
	pos, auth, lnurl = limits["pos"], limits["pos_auth"], limits["lnurl"]
	return [f"""# posd: {host}
server {{
{common(env, host)}	client_max_body_size {site.get('max_body', '256k')};
	limit_conn edge_conn {conn};
	modsecurity on;
	modsecurity_rules_file /etc/nginx/scuttle-edge/modsec/main.conf;
	# Wallets and the till parse posd's JSON errors; LNURL clients its
	# {{"status":"ERROR"}} form.
	error_page 403 = @denied;
	error_page 405 = @not_allowed;
	error_page 413 = @too_large;
	error_page 429 = @limited;

	location / {{
		limit_req zone=edge_pos burst={pos[1]} nodelay;
{proxy}	}}
	# Each callback makes barkd create a Lightning invoice.
	location ~ ^/api/v1/lnurlp/[^/]+/callback$ {{
		limit_req zone=edge_lnurl burst={lnurl[1]} nodelay;
		error_page 403 = @lnurl_denied;
		error_page 429 = @lnurl_limited;
{proxy}	}}
	# Owner sign-in, terminal pairing and store registration: guessable or
	# signature-checked, so few attempts per client.
	location ~ ^/api/v1/(owner/challenge|owner/login|pair|stores)$ {{
		limit_req zone=edge_pos_auth burst={auth[1]} nodelay;
{proxy}	}}
	# The operator API: token-authenticated by posd, and reachable only from
	# the operator's networks.
	location ^~ /api/v1/admin/ {{
{allow}		deny all;
		limit_req zone=edge_pos_auth burst={auth[1]} nodelay;
{proxy}	}}

	location @denied {{
		default_type application/json;
		return 403 '{{"error":"request refused"}}';
	}}
	location @not_allowed {{
		default_type application/json;
		return 405 '{{"error":"method not allowed"}}';
	}}
	location @too_large {{
		default_type application/json;
		return 413 '{{"error":"request too large"}}';
	}}
	location @limited {{
		default_type application/json;
		more_set_headers "Retry-After: 1";
		return 429 '{{"error":"too many requests"}}';
	}}
	location @lnurl_denied {{
		default_type application/json;
		more_set_headers "Access-Control-Allow-Origin: *";
		return 403 '{{"status":"ERROR","reason":"request refused"}}';
	}}
	location @lnurl_limited {{
		default_type application/json;
		more_set_headers "Access-Control-Allow-Origin: *" "Retry-After: 1";
		return 429 '{{"status":"ERROR","reason":"too many requests"}}';
	}}
}}

"""]


def load(path, assignments):
	with open(path, "rb") as f:
		env = tomllib.load(f)
	values = dict(a.split("=", 1) for a in assignments)
	for kind in ("ark", "posd"):
		for site in env.get(kind, []):
			site["host"] = site["host"].format(**values)
	return env


if __name__ == "__main__":
	args = sys.argv[1:]
	hosts_only = args[:1] == ["--hosts"]
	env = load(args[1] if hosts_only else args[0], args[2:] if hosts_only else args[1:])
	if hosts_only:
		print("\n".join(site["host"] for kind in ("ark", "posd") for site in env.get(kind, [])))
	else:
		sys.stdout.write(render(env))
